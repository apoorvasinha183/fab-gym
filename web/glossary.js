  // ---------------------------------------------------------------- search, A to Z
  const norm = (s) => s.toLowerCase();
  function find(q) {
    const k = norm(q.trim());
    const hit = (t) => !k || norm(t.term).includes(k) || (t.aliases || []).some((a) => norm(a).includes(k));
    return TERMS.filter(hit).sort((a, b) => a.term.localeCompare(b.term, "en", { sensitivity: "base" }));
  }

  // ---------------------------------------------------------------- words on the page link to their article
  // The longest name or alias that starts at a word boundary wins; each term is linked once per text.
  // A term whose name is also an everyday verb (link: false) is linked only by its other names.
  const NAMES = TERMS.flatMap((t) => (t.link === false ? [] : [t.term]).concat(t.aliases || []).map((n) => ({ n, lower: norm(n), term: t.term })))
    .filter((x) => x.n.length >= 3)
    .sort((a, b) => b.n.length - a.n.length);
  const wordChar = (c) => /[A-Za-z0-9]/.test(c || "");
  function linkify(text) {
    const out = [], done = new Set(), lower = norm(text);
    let buf = "", i = 0;
    while (i < text.length) {
      let m = null;
      if (!wordChar(text[i - 1])) {
        for (const x of NAMES) {
          if (lower.startsWith(x.lower, i) && !wordChar(text[i + x.n.length])) { m = x; break; }
        }
      }
      if (m) {
        const len = m.n.length;
        if (!done.has(m.term)) {
          if (buf) out.push({ text: buf }), (buf = "");
          out.push({ text: text.slice(i, i + len), term: m.term });
          done.add(m.term);
        } else buf += text.slice(i, i + len);
        i += len;
      } else buf += text[i++];
    }
    if (buf) out.push({ text: buf });
    return out;
  }

  // a term's other names as shown: codes such as P1 or D2 are left out
  function shownAliases(t) { return (t.aliases || []).filter((a) => !/^[A-Z]\d$/.test(a)); }

  const api = { TERMS, find, linkify, shownAliases };
